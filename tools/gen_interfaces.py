#!/usr/bin/env python3
"""Generate tools/dwrite_interfaces.tsv: the public COM interface surface of dwrite.h..dwrite_3.h.

Parses the IDL sources (method order == vtable order). Columns:
  interface  base  method  vtbl_index  introduced_in  declared_in(header)
vtbl_index counts IUnknown (QueryInterface=0, AddRef=1, Release=2). introduced_in is the SDK header
generation (dwrite.h = Win7, dwrite_1.h = Win7 platform update/Win8, dwrite_2.h = Win8.1, dwrite_3.h = Win10
with a per-interface refinement where known).
usage: gen_interfaces.py [idl_dir] [out.tsv]"""
import re, sys, os
idl_dir = sys.argv[1] if len(sys.argv) > 1 else "/home/iceisfun/work/wine/wine/include"
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "dwrite_interfaces.tsv")
FILES = [("dwrite.idl", "dwrite.h", "Win7"), ("dwrite_1.idl", "dwrite_1.h", "Win7 PU / Win8"),
         ("dwrite_2.idl", "dwrite_2.h", "Win8.1"), ("dwrite_3.idl", "dwrite_3.h", "Win10")]
# Refinement for dwrite_3.h (SDK documentation: minimum client per interface).
REFINE = {"IDWriteFactory3": "Win10 1607", "IDWriteFactory4": "Win10 1703", "IDWriteFactory5": "Win10 1709",
          "IDWriteFactory6": "Win10 1809", "IDWriteFactory7": "Win10 2004", "IDWriteFactory8": "Win11"}
ifaces = {}   # name -> dict(base, methods[], hdr, intro)
order = []
def strip(s):
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    return re.sub(r"//[^\n]*", "", s)
for fn, hdr, intro in FILES:
    src = strip(open(os.path.join(idl_dir, fn)).read())
    for m in re.finditer(r"\binterface\s+(\w+)\s*:\s*(\w+)\s*\{", src):
        name, base = m.group(1), m.group(2)
        i, depth = m.end(), 1
        while depth:
            c = src[i]
            depth += (c == "{") - (c == "}")
            i += 1
        body = src[m.end():i - 1]
        meths = []
        for stmt in re.split(r";", body):
            head = stmt.split("(")[0]
            if "(" not in stmt: continue
            head = re.sub(r"\[[^\]]*\]", " ", head)   # leading attributes such as [local]
            ids = re.findall(r"\w+", head)
            if ids: meths.append(ids[-1])
        ifaces[name] = dict(base=base, methods=meths, hdr=hdr, intro=REFINE.get(name, intro))
        order.append(name)
def base_count(n):
    if n == "IUnknown": return 3
    if n not in ifaces: return 3
    return base_count(ifaces[n]["base"]) + len(ifaces[n]["methods"])
rows = []
for n in order:
    start = base_count(ifaces[n]["base"])
    for k, meth in enumerate(ifaces[n]["methods"]):
        rows.append((n, ifaces[n]["base"], meth, start + k, ifaces[n]["intro"], ifaces[n]["hdr"]))
with open(out, "w") as f:
    f.write("interface\tbase\tmethod\tvtbl_index\tintroduced_in\theader\n")
    for r in rows: f.write("\t".join(map(str, r)) + "\n")
print(f"{len(order)} interfaces, {len(rows)} methods -> {out}")

# X-macro list of every interface whose IID the mingw headers provide (used by common/dw.c, dw_iid_table).
NO_HEADER = {"IDWriteBitmapRenderTarget2", "IDWriteBitmapRenderTarget3", "IDWriteFactory8", "IDWriteFontFace7", "IDWritePaintReader"}
inc = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(out))), "common", "dw_iids.inc")
with open(inc, "w") as f:
    f.write("/* generated by tools/gen_interfaces.py - do not edit */\n")
    for n in order:
        if n not in NO_HEADER: f.write(f"DWIID({n})\n")
print(f"wrote {inc}")
