"""Build the DirectWrite public-surface lists and the method -> dwrite.dll implementation map.

Outputs (all in tools/, regenerated by this script):
  public_surface.txt            one "IDWriteXxx::Method" per line: public methods of the interfaces that
                                Windows 10 build 19041 dwrite.dll implements (own methods only, IUnknown omitted)
  public_surface_by_header.txt  "IDWriteXxx::Method<TAB>header"
  public_surface_callbacks.txt  methods of client-implemented (callback) interfaces dwrite.dll only CALLS
  interface_support.tsv         interface, status (implemented / not-in-19041 / callback), implementing classes, evidence
  method_impl_map.tsv           interface, method, vtbl_index, status, dwrite.dll functions implementing it

Truth source: the Corpus Explorer API (default http://docker1.dev.moonlightcompanies.com:8765), module "dwrite".
  * /api/symbols/dwrite lists every symbol; virtual methods carry MSVC-decorated names
    (?Method@Class@@UEAA...  or an adjustor thunk ?Method@Class@@W7EAA...), which give Class::Method plus the
    parameter types used to tell overloads apart.
  * /api/function/dwrite/<rva>/decomp of every QueryInterface body gives the interface list per class
    (decorated template arguments and explicit IID comparisons); that is how support is decided.

Resumable: API results are cached as JSON in --cache (default $TMPDIR/dwrite_method_map_cache); rerun any time.
At most 6 concurrent API requests are made.
usage: build_method_map.py [--api URL] [--cache DIR] [--idl-dir DIR] [--refresh]
"""
