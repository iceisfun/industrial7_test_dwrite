# ---------------------------------------------------------------- API access
def fetch(url, tries=3):
    last = None
    for _ in range(tries):
        try:
            with urllib.request.urlopen(url, timeout=60) as r:
                return r.read().decode("utf-8", "replace")
        except Exception as e:           # network flake: retry
            last = e
    raise RuntimeError("fetch failed %s: %s" % (url, last))

def cached(cache, name, producer, refresh):
    p = os.path.join(cache, name)
    if not refresh and os.path.exists(p):
        with open(p) as f:
            return json.load(f)
    v = producer()
    tmp = p + ".tmp"
    with open(tmp, "w") as f:
        json.dump(v, f)
    os.replace(tmp, p)
    return v

def load_symbols(api, cache, refresh):
    def prod():
        first = json.loads(fetch("%s/api/symbols/dwrite?limit=1000&offset=0" % api))
        total = first["total"]
        offs = list(range(1000, total, 1000))
        items = list(first["items"])
        with cf.ThreadPoolExecutor(MAX_WORKERS) as ex:
            for d in ex.map(lambda o: json.loads(fetch("%s/api/symbols/dwrite?limit=1000&offset=%d" % (api, o))), offs):
                items += d["items"]
        return items
    return cached(cache, "symbols.json", prod, refresh)

def load_decomps(api, cache, rvas, refresh):
    """Headers (everything before the function body) of the decompilation of each rva, resumable per rva."""
    p = os.path.join(cache, "qi_decomps.json")
    have = {} if refresh or not os.path.exists(p) else json.load(open(p))
    todo = [r for r in rvas if str(r) not in have]
    def one(r):
        t = fetch("%s/api/function/dwrite/0x%x/decomp" % (api, r))
        return r, t
    with cf.ThreadPoolExecutor(MAX_WORKERS) as ex:
        for n, (r, t) in enumerate(ex.map(one, todo)):
            have[str(r)] = t
            if n % 20 == 19:
                json.dump(have, open(p + ".tmp", "w")); os.replace(p + ".tmp", p)
    json.dump(have, open(p + ".tmp", "w")); os.replace(p + ".tmp", p)
    return have

# ---------------------------------------------------------------- IDL parsing (method order == vtable order)
def strip_c(s):
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    return re.sub(r"//[^\n]*", "", s)

def parse_idl(idl_dir):
    """-> (iid map guid->name, {iface: {base, hdr, methods:[(name, ret, params_text)]}}, order)"""
    files = [("dwrite.idl", "dwrite.h"), ("dwrite_1.idl", "dwrite_1.h"), ("dwrite_2.idl", "dwrite_2.h"), ("dwrite_3.idl", "dwrite_3.h")]
    iid, ifs, order = {}, {}, []
    for fn, hdr in files:
        raw = open(os.path.join(idl_dir, fn)).read()
        for m in re.finditer(r"uuid\(([0-9a-fA-F-]{36})\)[^{};]*?\]\s*interface\s+(\w+)", raw, re.S):
            iid[m.group(1).lower()] = m.group(2)
        src = strip_c(raw)
        for m in re.finditer(r"\binterface\s+(\w+)\s*:\s*(\w+)\s*\{", src):
            name, base = m.group(1), m.group(2)
            i, depth = m.end(), 1
            while depth:
                c = src[i]; depth += (c == "{") - (c == "}"); i += 1
            body = src[m.end():i - 1]
            meths = []
            for stmt in body.split(";"):
                if "(" not in stmt: continue
                head, _, rest = stmt.partition("(")
                head = re.sub(r"\[[^\]]*\]", " ", head)
                ids = re.findall(r"\w+", head)
                if not ids: continue
                meths.append((ids[-1], " ".join(ids[:-1]), rest.rsplit(")", 1)[0]))
            ifs[name] = dict(base=base, hdr=hdr, methods=meths)
            order.append(name)
    return iid, ifs, order

# ---------------------------------------------------------------- MSVC-decorated name handling
VIRT = re.compile(r"^\?(?P<m>[A-Za-z_][A-Za-z0-9_]*)@(?P<c>[A-Za-z_][A-Za-z0-9_]*)@@(?P<k>U|W(?:[0-9]|[A-P]+@))EAA")

def mangled_types(name):
    """Identifier set of struct/enum/class types appearing in a decorated name (back-references resolved)."""
    m = re.match(r"^\?([^@]+)@([^@]+)@@", name)
    if not m: return set()
    table = [m.group(1), m.group(2)]
    s = re.sub(r"^(?:U|W(?:[0-9]|[A-P]+@))EAA", "", name[m.end():])   # virtual / adjustor-thunk calling convention prefix
    out, i = set(), 0
    while i < len(s):
        c = s[i]
        if (c in "UTV" or s.startswith("W4", i)) and (i == 0 or True):
            j = i + (2 if s.startswith("W4", i) else 1)
            # qualified name: sequence of (digit backref | ident@) ended by '@'
            names, k = [], j
            while k < len(s):
                if s[k].isdigit(): names.append(table[int(s[k])] if int(s[k]) < len(table) else "?"); k += 1
                elif s[k] == "@": k += 1; break
                else:
                    e = s.find("@", k)
                    if e < 0: break
                    nm = s[k:e]
                    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", nm): names = []; break
                    if nm not in table and len(table) < 10: table.append(nm)
                    names.append(nm); k = e + 1
            if names and re.fullmatch(r"[A-Za-z_]\w*", names[0] or ""):
                out.add(names[0]); i = k; continue
        i += 1
    return out

ALIAS = {"REFIID": "_GUID", "REFGUID": "_GUID", "GUID": "_GUID", "FILETIME": "_FILETIME", "LOGFONTW": "tagLOGFONTW",
         "HMONITOR": "HMONITOR__", "HDC": "HDC__", "HBITMAP": "HBITMAP__", "DWRITE_COLOR_F": "_D3DCOLORVALUE",
         "D2D1_COLOR_F": "_D3DCOLORVALUE", "D2D_COLOR_F": "_D3DCOLORVALUE", "DWRITE_MATRIX": "DWRITE_MATRIX",
         "DWRITE_PANOSE": "DWRITE_PANOSE", "D2D_POINT_2F": "D2D_POINT_2F", "D2D1_POINT_2F": "D2D_POINT_2F",
         "D2D_MATRIX_3X2_F": "D2D_MATRIX_3X2_F", "D2D1_MATRIX_3X2_F": "D2D_MATRIX_3X2_F"}
TYPE_RX = re.compile(r"\b(DWRITE_\w+|IDWrite\w+|ID2D1\w+|D2D1?_\w+|FILETIME|REFIID|REFGUID|GUID|LOGFONTW|HMONITOR|HDC|HBITMAP|IStream|IUnknown)\b")

def idl_types(ret, params):
    out = set()
    for t in TYPE_RX.findall(ret + " " + params):
        t = ALIAS.get(t, t)
        if t == "IUnknown":      # IUnknown** out-params appear as PEAPEAUIUnknown@@
            t = "IUnknown"
        out.add(t)
    return out

def score(m_types, p_types):
    mt = {t for t in m_types if t not in ("_GUID_dummy",)}
    return len(mt & p_types) - 0.5 * len(mt - p_types) - 0.5 * len(p_types - mt)

# ---------------------------------------------------------------- QueryInterface evidence
def qi_class(sig):
    for rx in (r"(\w+)::QueryInterface", r"ComObject<(?:class )?(\w+),", r"ComObjectBase<(?:class )?ComInterfaceList<(?:class )?(\w+)"):
        m = re.search(rx, sig)
        if m and m.group(1) not in ("ComObject", "ComObjectBase"): return m.group(1)
    m = re.search(r"QueryInterfaceImpl<(?:class )?ComObject<(?:class )?(\w+),", sig)
    return m.group(1) if m else None

def qi_evidence(symbols, decomps, iidmap):
    rvas = sorted({s["rva"] for s in symbols if "QueryInterface" in s["name"] and s["name"].startswith("?")
                   and "Helper" not in s["name"]})
    ev = {}
    for r in rvas:
        t = decomps.get(str(r), "")
        hdr = t.split("\n{")[0]
        sig = " ".join(" ".join(re.findall(r"/\*(.*?)\*/", hdr, re.S)).split())
        cls = qi_class(sig)
        if not cls:
            nm = next((s["name"] for s in symbols if s["rva"] == r and s["name"].startswith("?")), "")
            cls = qi_class(nm.replace("@", ","))
        if not cls: continue
        if cls.startswith("LocalizedStringsWith"): cls = "DWriteLocalizedStrings"
        names = set(re.findall(r"IDWrite\w+", sig))
        for g in re.findall(r"_GUID_([0-9a-f]{8})_([0-9a-f]{4})_([0-9a-f]{4})_([0-9a-f]{4})_([0-9a-f]{12})", t):
            n = iidmap.get("-".join(g))
            if n: names.add(n)
        ev.setdefault(cls, set()).update(names)
    return ev

# ---------------------------------------------------------------- main
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--api", default="http://docker1.dev.moonlightcompanies.com:8765")
    ap.add_argument("--cache", default=os.path.join(os.environ.get("TMPDIR", "/tmp"), "dwrite_method_map_cache"))
    ap.add_argument("--idl-dir", default="/home/iceisfun/work/wine/wine/include")
    ap.add_argument("--refresh", action="store_true")
    a = ap.parse_args()
    os.makedirs(a.cache, exist_ok=True)

    iidmap, ifs, order = parse_idl(a.idl_dir)
    symbols = load_symbols(a.api, a.cache, a.refresh)
    qi_rvas = sorted({s["rva"] for s in symbols if "QueryInterface" in s["name"] and s["name"].startswith("?")
                      and "Helper" not in s["name"]})
    decomps = load_decomps(a.api, a.cache, qi_rvas, a.refresh)
    evidence = qi_evidence(symbols, decomps, iidmap)

    # tsv rows (the checked-in interface list) define method set + order
    rows = [l.rstrip("\n").split("\t") for l in open(os.path.join(HERE, "dwrite_interfaces.tsv"))][1:]
    meths = {}
    for r in rows:
        meths.setdefault(r[0], []).append(r)
    tsv_order = list(dict.fromkeys(r[0] for r in rows))

    # virtual-method symbols by class: class -> method -> [(rva, name, kind)]
    by_class = {}
    for s in symbols:
        n = s["name"]
        m = VIRT.match(n)
        if not m: continue
        kind = "virtual" if m.group("k") == "U" else "thunk"
        by_class.setdefault(m.group("c"), {}).setdefault(m.group("m"), []).append((s["rva"], n, kind))
    # dedupe identical (rva,name)
    for c in by_class:
        for mm in by_class[c]:
            by_class[c][mm] = sorted(set(by_class[c][mm]))

    support, impl_lines, surf, surf_hdr, cb_lines, map_rows = [], [], [], [], [], []
    for iface in tsv_order:
        classes = IMPL.get(iface)
        if iface in CALLBACK:
            status = "callback"
        elif classes:
            status = "implemented"
        else:
            status = "not-in-19041"
        evid = ""
        if classes:
            seen = sorted({c for c in classes if iface in evidence.get(c, ())})
            evid = "QI:" + (",".join(seen) if seen else "NOT-SEEN-IN-QI-DECOMP")
        elif status == "not-in-19041":
            evid = NOTE_ABSENT.get(iface, "no implementing class found in dwrite.dll symbols")
        else:
            evid = "client-implemented; dwrite.dll only calls through it"
        base = meths[iface][0][1]
        support.append((iface, status, ",".join(classes or []), evid))
        for r in meths[iface]:
            line = "%s::%s" % (iface, r[2])
            if status == "implemented":
                surf.append(line); surf_hdr.append("%s\t%s" % (line, r[5]))
            elif status == "callback":
                cb_lines.append("%s\t%s" % (line, r[5]))
        if status != "implemented": continue
        imeths = ifs.get(iface, {}).get("methods", [])
        meta = {m[0]: m for m in imeths}
        for r in meths[iface]:
            vname = r[2]                       # name as in the interface table (COBJMACROS spelling, overload '_' kept)
            mname = SYMNAME.get(vname, vname.rstrip("_"))   # name as decorated in dwrite.dll
            ret, params = (meta[vname][1], meta[vname][2]) if vname in meta else ("", "")
            ptypes = idl_types(ret, params)
            found, how = [], "unresolved"
            for c in classes:
                cands = by_class.get(c, {}).get(mname, [])
                virt = [x for x in cands if x[2] == "virtual"]
                thunks = [x for x in cands if x[2] == "thunk"]
                if not virt and not thunks: continue
                pool = virt or thunks
                # group overloads by decorated name; best score wins, ties kept
                scored = sorted(((score(mangled_types(n), ptypes), rva, n) for rva, n, _ in pool), key=lambda t: -t[0])
                top = scored[0][0]
                best = [t for t in scored if t[0] == top]
                uniq_names = {x[1] for x in pool}
                if len(uniq_names) == 1: h = "unique"
                elif len(best) == 1: h = "overload-by-signature"
                else: h = "ambiguous"
                if how == "unresolved" or h == "unique": how = h
                elif h == "ambiguous": how = "ambiguous"
                for _, rva, n in best:
                    found.append("%s::%s@0x%x" % (c, mname, rva))
                for rva, n, k in thunks:
                    if not virt: continue
                    # adjustor thunks for secondary vtables; record those whose decorated name matches the choice
                    if mangled_types(n) == mangled_types(best[0][2]):
                        found.append("%s::%s@0x%x[thunk]" % (c, mname, rva))
            map_rows.append((iface, vname, r[3], how if found else "unresolved", ";".join(dict.fromkeys(found))))

    def w(name, lines):
        with open(os.path.join(HERE, name), "w") as f:
            f.write("\n".join(lines) + "\n")
    w("public_surface.txt", surf)
    w("public_surface_by_header.txt", surf_hdr)
    w("public_surface_callbacks.txt", cb_lines)
    w("interface_support.tsv", ["interface\tstatus\timplementing_classes\tevidence"] + ["\t".join(x) for x in support])
    w("method_impl_map.tsv", ["interface\tmethod\tvtbl_index\tstatus\tdwrite_functions(Class::Method@rva)"] +
      ["\t".join(x) for x in map_rows])

    n_unres = sum(1 for x in map_rows if x[3] == "unresolved")
    n_amb = sum(1 for x in map_rows if x[3] == "ambiguous")
    print("interfaces implemented: %d" % sum(1 for s in support if s[1] == "implemented"))
    print("interfaces not in 19041: %d  callback: %d" % (sum(1 for s in support if s[1] == "not-in-19041"),
                                                      sum(1 for s in support if s[1] == "callback")))
    print("public methods: %d  mapped: %d  unresolved: %d  ambiguous: %d" % (len(surf), len(map_rows) - n_unres, n_unres, n_amb))
    bad = [s for s in support if s[1] == "implemented" and "NOT-SEEN" in s[3]]
    for s in bad: print("WARNING: no QI evidence for", s[0], s[2])

if __name__ == "__main__":
    main()
